# ── 平台检测 ─────────────────────────────────────────────────────────────────
IS_MAC = platform.system() == "Darwin"


def ping_ip(ip: str, timeout_sec: int = 2) -> bool:
    """发一个 ICMP Echo，返回是否可达。"""
    if IS_MAC:
        # macOS: -W 单位毫秒
        cmd = ["ping", "-c", "1", "-W", str(timeout_sec * 1000), ip]
    else:
        # Linux: -W 单位秒
        cmd = ["ping", "-c", "1", "-W", str(timeout_sec), ip]
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=timeout_sec + 2)
        return r.returncode == 0
    except Exception:
        return False


def traceroute_hops(ip: str, max_hops: int = 30, timeout_sec: int = 30):
    """
    跑 traceroute，返回 (跳数, 最后一跳IP)。
    跳数 = 实际路径行数（排除 header）。
    """
    # -n 不做 DNS 解析，-m 最大跳数，-w 每跳等待秒数，-q 每跳探测包数量
    if IS_MAC:
        cmd = ["traceroute", "-n", "-m", str(max_hops), "-w", "1", "-q", "1", ip]
    else:
        cmd = ["traceroute", "-n", "-m", str(max_hops), "-w", "1", "-q", "1", ip]
    try:
        r = subprocess.run(
            cmd, capture_output=True, text=True, timeout=timeout_sec
        )
        lines = r.stdout.strip().splitlines()
        # 第 0 行是 "traceroute to ..." 头部，后面每行一跳
        hop_lines = [l for l in lines[1:] if l.strip()]
        hops = len(hop_lines)

        # 提取最后一跳 IP（第一个看起来像 IP 的 token）
        last_hop_ip = "N/A"
        if hop_lines:
            tokens = hop_lines[-1].split()
            for tok in tokens:
                parts = tok.split(".")
                if len(parts) == 4 and all(p.isdigit() for p in parts):
                    last_hop_ip = tok
                    break
        return hops, last_hop_ip
    except subprocess.TimeoutExpired:
        return None, "timeout"
    except Exception as e:
        return None, f"error:{e}"


def check_ip(ip: str, ping_timeout: int, trace_timeout: int, max_hops: int = 30) -> dict:
    ip = ip.strip()
    reachable = ping_ip(ip, ping_timeout)
    hops, last_hop = (None, "N/A")
    if reachable:
        hops, last_hop = traceroute_hops(ip, max_hops=max_hops, timeout_sec=trace_timeout)
    return {
        "ip": ip,
        "reachable": "yes" if reachable else "no",
        "hops": hops if hops is not None else "N/A",
        "last_hop_ip": last_hop,
    }


def ip_sort_key(r: dict):
    try:
        return tuple(int(x) for x in r["ip"].split("."))
    except ValueError:
        return (999, 999, 999, 999)


def main():
    parser = argparse.ArgumentParser(description="并行 Ping + Traceroute 测试工具")
    parser.add_argument("--workers", type=int, default=50, help="并发线程数 (默认 50)")
    parser.add_argument("--output", default="ip_results.csv", help="输出 CSV 文件名 (默认 ip_results.csv)")
    parser.add_argument("--ping-timeout", type=int, default=2, help="ping 超时秒数 (默认 2)")
    parser.add_argument("--trace-timeout", type=int, default=30, help="traceroute 超时秒数 (默认 30)")
    parser.add_argument("--max-hops", type=int, default=30, help="traceroute 最大跳数 (默认 30)")
    args = parser.parse_args()

    total = len(IPS)
    print(f"[{datetime.now().strftime('%H:%M:%S')}] 共 {total} 个 IP，并发 {args.workers} 线程")
    print(f"  ping 超时={args.ping_timeout}s  traceroute 超时={args.trace_timeout}s  max-hops={args.max_hops}")
    print(f"  结果将写入: {args.output}\n")

    results = []
    completed = 0

    with ThreadPoolExecutor(max_workers=args.workers) as executor:
        futures = {
            executor.submit(check_ip, ip, args.ping_timeout, args.trace_timeout, args.max_hops): ip
            for ip in IPS
        }
        for future in as_completed(futures):
            row = future.result()
            results.append(row)
            completed += 1
            # 实时进度
            status = f"✓ {row['hops']} hops" if row["reachable"] == "yes" else "✗ unreachable"
            print(f"  [{completed:4d}/{total}] {row['ip']:<20} {status}", flush=True)

    # 按 IP 数值排序
    results.sort(key=ip_sort_key)

    # 写 CSV
    fieldnames = ["ip", "reachable", "hops", "last_hop_ip"]
    with open(args.output, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(results)

    # 统计摘要
    reachable_list = [r for r in results if r["reachable"] == "yes"]
    hop_vals = [r["hops"] for r in reachable_list if isinstance(r["hops"], int)]
    print(f"\n{'─'*50}")
    print(f"完成！结果已写入: {args.output}")
    print(f"可达: {len(reachable_list)}/{total}")
    if hop_vals:
        print(f"跳数范围: min={min(hop_vals)}  max={max(hop_vals)}  avg={sum(hop_vals)/len(hop_vals):.1f}")
    print(f"{'─'*50}")


if __name__ == "__main__":
    main()
